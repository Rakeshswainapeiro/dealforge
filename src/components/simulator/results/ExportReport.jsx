import React from "react";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import { FileDown, FileText, FileSpreadsheet } from "lucide-react";

export default function ExportReport({ simulation, companies }) {
  const exportJSON = () => {
    const data = JSON.stringify(simulation, null, 2);
    const blob = new Blob([data], { type: 'application/json' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${simulation.name}_simulation.json`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const exportMarkdown = () => {
    const acquirer = companies.find(c => c.id === simulation.merger_parties?.acquirer_id);
    const targets = simulation.merger_parties?.target_ids?.map(id => 
      companies.find(c => c.id === id)
    ).filter(Boolean) || [];

    const report = `# Merger Simulation Report
## ${simulation.name}

${simulation.description || ''}

### Market Definition
- **Product Market:** ${simulation.market_definition?.product_market || 'N/A'}
- **Geographic Market:** ${simulation.market_definition?.geographic_market || 'N/A'}
- **Time Window:** ${simulation.market_definition?.time_window || 'N/A'}
- **Pricing Model:** ${simulation.pricing_model || 'Bertrand'}

### Merger Parties
- **Acquirer:** ${acquirer?.name || 'N/A'}
- **Target(s):** ${targets.map(t => t.name).join(', ') || 'N/A'}

### Key Metrics
- **Status:** ${simulation.status}
- **Created:** ${new Date(simulation.created_date).toLocaleDateString()}
- **Last Updated:** ${new Date(simulation.updated_date).toLocaleDateString()}

---
*Generated by DealForge Merger Simulator*`;

    const blob = new Blob([report], { type: 'text/markdown' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${simulation.name}_report.md`;
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="space-y-6">
      <Card className="border-slate-200">
        <CardHeader className="border-b border-slate-100">
          <CardTitle>Export Options</CardTitle>
        </CardHeader>
        <CardContent className="p-6">
          <div className="grid md:grid-cols-3 gap-4">
            <Button
              onClick={exportJSON}
              variant="outline"
              className="h-32 flex-col gap-3"
            >
              <FileText className="w-8 h-8 text-slate-600" />
              <div className="text-center">
                <p className="font-semibold">JSON Data</p>
                <p className="text-xs text-slate-500">Complete simulation data</p>
              </div>
            </Button>

            <Button
              onClick={exportMarkdown}
              variant="outline"
              className="h-32 flex-col gap-3"
            >
              <FileDown className="w-8 h-8 text-slate-600" />
              <div className="text-center">
                <p className="font-semibold">Markdown Report</p>
                <p className="text-xs text-slate-500">Executive summary</p>
              </div>
            </Button>

            <Button
              variant="outline"
              className="h-32 flex-col gap-3"
              disabled
            >
              <FileSpreadsheet className="w-8 h-8 text-slate-400" />
              <div className="text-center">
                <p className="font-semibold">CSV Export</p>
                <p className="text-xs text-slate-500">Coming soon</p>
              </div>
            </Button>
          </div>
        </CardContent>
      </Card>

      <Card className="border-slate-200">
        <CardHeader className="border-b border-slate-100">
          <CardTitle>Regulator Brief</CardTitle>
        </CardHeader>
        <CardContent className="p-6">
          <p className="text-slate-600 mb-4">
            Generate a comprehensive report suitable for regulatory submissions, including:
          </p>
          <ul className="list-disc list-inside space-y-2 text-slate-700">
            <li>Executive summary of competitive effects</li>
            <li>Market definition and structure analysis</li>
            <li>Unilateral and coordinated effects assessment</li>
            <li>Efficiency claims and supporting data</li>
            <li>Sensitivity analysis and robustness checks</li>
            <li>Assumptions registry with full transparency</li>
          </ul>
          <Button className="mt-6 bg-teal-600 hover:bg-teal-700" onClick={exportMarkdown}>
            <FileDown className="w-4 h-4 mr-2" />
            Generate Regulator Brief
          </Button>
        </CardContent>
      </Card>
    </div>
  );
}