import React from "react";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import { ArrowLeft, Pencil, Trash2, FileText, Target, TrendingUp, Building2 } from "lucide-react";
import { Badge } from "@/components/ui/badge";
import ProFormaTable from "./ProFormaTable";
import SynergyBreakdown from "./SynergyBreakdown";
import AIAnalysis from "./AIAnalysis";
import RiskAssessment from "../shared/RiskAssessment";

export default function ScenarioDetails({ scenario, companies, onBack, onEdit, onDelete, canModify = true }) {
  const acquirer = companies.find(c => c.id === scenario.acquirer_id);
  const targets = scenario.target_ids?.map(id => companies.find(c => c.id === id)).filter(Boolean) || [];
  const primaryTarget = targets[0];

  const totalDealValue = primaryTarget ? (
    primaryTarget.market_cap * (1 + (scenario.deal_structure?.premium || 0) / 100)
  ) : 0;

  const cashComponent = totalDealValue * (scenario.deal_structure?.cash_percentage || 0) / 100;
  const stockComponent = totalDealValue * (scenario.deal_structure?.stock_percentage || 0) / 100;

  const totalSynergies = (scenario.synergies?.revenue_synergies || 0) + (scenario.synergies?.cost_synergies || 0);
  const netSynergies = totalSynergies - (scenario.synergies?.integration_costs || 0);
  const synergyAsPercent = primaryTarget?.revenue ? ((totalSynergies / primaryTarget.revenue) * 100).toFixed(1) : 0;

  const getStrategicRationale = () => {
    const rationale = [];
    
    const combinedMarketShare = (acquirer?.market_share || 0) + (primaryTarget?.market_share || 0);
    if (combinedMarketShare > 0) {
      rationale.push({
        title: "Market Position Enhancement",
        description: `Combined entity will control ${combinedMarketShare.toFixed(1)}% market share, strengthening competitive position.`
      });
    }

    if (scenario.synergies?.revenue_synergies > 0) {
      rationale.push({
        title: "Revenue Growth Opportunity",
        description: `Projected $${scenario.synergies.revenue_synergies.toFixed(0)}M in revenue synergies through cross-selling and market expansion.`
      });
    }

    if (scenario.synergies?.cost_synergies > 0) {
      rationale.push({
        title: "Operational Efficiency",
        description: `Expected $${scenario.synergies.cost_synergies.toFixed(0)}M in cost savings from economies of scale and operational consolidation.`
      });
    }

    if (scenario.deal_structure?.cash_percentage > 60) {
      rationale.push({
        title: "Cash-Heavy Structure",
        description: "Predominantly cash consideration provides certainty for target shareholders and faster closing."
      });
    } else if (scenario.deal_structure?.stock_percentage > 60) {
      rationale.push({
        title: "Stock-Heavy Structure",
        description: "Significant stock component aligns target shareholders with combined entity's future performance."
      });
    }

    if (acquirer?.sector === primaryTarget?.sector) {
      rationale.push({
        title: "Sector Consolidation",
        description: `Horizontal integration within ${acquirer.sector} sector enables synergies and market leadership.`
      });
    } else {
      rationale.push({
        title: "Diversification Strategy",
        description: `Cross-sector acquisition expands into ${primaryTarget?.sector} market, reducing business concentration risk.`
      });
    }

    return rationale;
  };

  const strategicRationale = getStrategicRationale();

  const generateReport = () => {
    const report = `# M&A Analysis Report
## ${scenario.name}

### Executive Summary
${scenario.name} represents a strategic combination between ${acquirer?.name || 'N/A'} and ${primaryTarget?.name || 'Target'}.

### Deal Structure
- **Acquirer:** ${acquirer?.name || 'N/A'}
- **Target(s):** ${targets.map(t => t.name).join(', ')}
- **Total Deal Value:** $${(totalDealValue / 1000).toFixed(1)}B
- **Premium:** ${scenario.deal_structure?.premium || 0}%
- **Consideration Mix:** ${scenario.deal_structure?.cash_percentage || 0}% Cash / ${scenario.deal_structure?.stock_percentage || 0}% Stock
- **New Debt:** $${scenario.deal_structure?.new_debt || 0}M

### Strategic Rationale
${strategicRationale.map(r => `**${r.title}**\n${r.description}`).join('\n\n')}

### Synergies
- **Revenue Synergies:** $${scenario.synergies?.revenue_synergies || 0}M
- **Cost Synergies:** $${scenario.synergies?.cost_synergies || 0}M
- **Total Gross Synergies:** $${totalSynergies}M
- **Integration Costs:** $${scenario.synergies?.integration_costs || 0}M
- **Net Synergies:** $${netSynergies}M

### Key Assumptions
- **WACC:** ${scenario.assumptions?.wacc || 0}%
- **Tax Rate:** ${scenario.assumptions?.tax_rate || 0}%
- **Expected Closing:** ${scenario.assumptions?.closing_date || 'N/A'}

---
*Generated by DealForge M&A Platform*`;

    const blob = new Blob([report], { type: 'text/markdown' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${scenario.name.replace(/\s+/g, '_')}_Report.md`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  const statusColors = {
    draft: "bg-slate-100 text-slate-800",
    active: "bg-teal-100 text-teal-800",
    completed: "bg-emerald-100 text-emerald-800",
    archived: "bg-amber-100 text-amber-800",
  };

  return (
    <div className="space-y-6">
      <div className="flex flex-col md:flex-row justify-between items-start md:items-center gap-4">
        <div className="flex items-center gap-4">
          <Button variant="outline" size="icon" onClick={onBack}>
            <ArrowLeft className="w-4 h-4" />
          </Button>
          <div>
            <div className="flex items-center gap-3">
              <h2 className="text-2xl font-bold text-slate-900">{scenario.name}</h2>
              <Badge className={statusColors[scenario.status]}>
                {scenario.status}
              </Badge>
            </div>
            <p className="text-slate-600 mt-1">Detailed analysis and pro-forma calculations</p>
          </div>
        </div>
        {canModify && (
          <div className="flex gap-3">
            <Button variant="outline" onClick={generateReport} className="gap-2">
              <FileText className="w-4 h-4" />
              Export Report
            </Button>
            <Button variant="outline" onClick={() => onEdit(scenario)} className="gap-2">
              <Pencil className="w-4 h-4" />
              Edit
            </Button>
            <Button 
              variant="outline" 
              onClick={() => {
                if (window.confirm(`Delete ${scenario.name}?`)) {
                  onDelete();
                }
              }}
              className="gap-2 text-red-600 hover:text-red-700"
            >
              <Trash2 className="w-4 h-4" />
              Delete
            </Button>
          </div>
        )}
      </div>

      <div className="grid md:grid-cols-3 gap-4">
        <Card className="border-slate-200 shadow-sm">
          <CardContent className="p-6">
            <div className="flex items-center gap-2 mb-2">
              <TrendingUp className="w-4 h-4 text-teal-600" />
              <span className="text-sm text-slate-600">Total Deal Value</span>
            </div>
            <p className="text-3xl font-bold text-slate-900">
              ${(totalDealValue / 1000).toFixed(1)}B
            </p>
            <p className="text-xs text-slate-500 mt-1">
              {scenario.deal_structure?.premium || 0}% premium to market
            </p>
          </CardContent>
        </Card>

        <Card className="border-slate-200 shadow-sm">
          <CardContent className="p-6">
            <div className="flex items-center gap-2 mb-2">
              <Target className="w-4 h-4 text-emerald-600" />
              <span className="text-sm text-slate-600">Net Synergies</span>
            </div>
            <p className="text-3xl font-bold text-emerald-600">
              ${netSynergies.toFixed(0)}M
            </p>
            <p className="text-xs text-slate-500 mt-1">
              {synergyAsPercent}% of target revenue
            </p>
          </CardContent>
        </Card>

        <Card className="border-slate-200 shadow-sm">
          <CardContent className="p-6">
            <div className="flex items-center gap-2 mb-2">
              <Building2 className="w-4 h-4 text-blue-600" />
              <span className="text-sm text-slate-600">Combined Market Share</span>
            </div>
            <p className="text-3xl font-bold text-blue-600">
              {((acquirer?.market_share || 0) + (primaryTarget?.market_share || 0)).toFixed(1)}%
            </p>
            <p className="text-xs text-slate-500 mt-1">
              Post-merger market position
            </p>
          </CardContent>
        </Card>
      </div>

      <Card className="border-slate-200 shadow-sm">
        <CardHeader className="border-b border-slate-100">
          <CardTitle className="flex items-center gap-2">
            <Target className="w-5 h-5 text-teal-600" />
            Strategic Rationale
          </CardTitle>
        </CardHeader>
        <CardContent className="p-6">
          <div className="grid md:grid-cols-2 gap-4">
            {strategicRationale.map((item, idx) => (
              <div key={idx} className="p-4 bg-slate-50 rounded-lg border border-slate-200">
                <h4 className="font-semibold text-slate-900 mb-2 flex items-center gap-2">
                  <span className="w-6 h-6 bg-teal-100 text-teal-700 rounded-full flex items-center justify-center text-sm font-bold">
                    {idx + 1}
                  </span>
                  {item.title}
                </h4>
                <p className="text-sm text-slate-600">{item.description}</p>
              </div>
            ))}
          </div>
        </CardContent>
      </Card>

      <div className="grid lg:grid-cols-2 gap-6">
        <Card className="border-teal-200 shadow-sm bg-teal-50">
          <CardHeader className="border-b border-teal-100">
            <CardTitle className="flex items-center gap-2">
              <Building2 className="w-5 h-5 text-teal-600" />
              Acquirer
            </CardTitle>
          </CardHeader>
          <CardContent className="p-6">
            {acquirer ? (
              <div className="space-y-3">
                <div>
                  <h3 className="text-xl font-bold text-slate-900">{acquirer.name}</h3>
                  {acquirer.ticker && (
                    <Badge variant="outline" className="mt-1">{acquirer.ticker}</Badge>
                  )}
                </div>
                <div className="grid grid-cols-2 gap-3 text-sm">
                  <div>
                    <p className="text-slate-600">Market Cap</p>
                    <p className="font-semibold text-slate-900">${(acquirer.market_cap / 1000).toFixed(1)}B</p>
                  </div>
                  <div>
                    <p className="text-slate-600">Revenue</p>
                    <p className="font-semibold text-slate-900">${(acquirer.revenue / 1000).toFixed(1)}B</p>
                  </div>
                  <div>
                    <p className="text-slate-600">EBITDA</p>
                    <p className="font-semibold text-slate-900">${acquirer.ebitda.toFixed(0)}M</p>
                  </div>
                  <div>
                    <p className="text-slate-600">Market Share</p>
                    <p className="font-semibold text-slate-900">{acquirer.market_share || 0}%</p>
                  </div>
                </div>
              </div>
            ) : (
              <p className="text-slate-500">No acquirer data</p>
            )}
          </CardContent>
        </Card>

        <Card className="border-amber-200 shadow-sm bg-amber-50">
          <CardHeader className="border-b border-amber-100">
            <CardTitle className="flex items-center gap-2">
              <Target className="w-5 h-5 text-amber-600" />
              Target{targets.length > 1 ? 's' : ''}
            </CardTitle>
          </CardHeader>
          <CardContent className="p-6">
            {targets.length > 0 ? (
              <div className="space-y-4">
                {targets.map((target, idx) => (
                  <div key={idx} className="space-y-3">
                    <div>
                      <h3 className="text-xl font-bold text-slate-900">{target.name}</h3>
                      {target.ticker && (
                        <Badge variant="outline" className="mt-1">{target.ticker}</Badge>
                      )}
                    </div>
                    <div className="grid grid-cols-2 gap-3 text-sm">
                      <div>
                        <p className="text-slate-600">Market Cap</p>
                        <p className="font-semibold text-slate-900">${(target.market_cap / 1000).toFixed(1)}B</p>
                      </div>
                      <div>
                        <p className="text-slate-600">Revenue</p>
                        <p className="font-semibold text-slate-900">${(target.revenue / 1000).toFixed(1)}B</p>
                      </div>
                      <div>
                        <p className="text-slate-600">EBITDA</p>
                        <p className="font-semibold text-slate-900">${target.ebitda.toFixed(0)}M</p>
                      </div>
                      <div>
                        <p className="text-slate-600">Market Share</p>
                        <p className="font-semibold text-slate-900">{target.market_share || 0}%</p>
                      </div>
                    </div>
                    {idx < targets.length - 1 && <div className="border-t border-amber-200 pt-4" />}
                  </div>
                ))}
              </div>
            ) : (
              <p className="text-slate-500">No target data</p>
            )}
          </CardContent>
        </Card>
      </div>

      <div className="grid lg:grid-cols-2 gap-6">
        <Card className="border-slate-200">
          <CardHeader className="border-b border-slate-100">
            <CardTitle>Deal Structure</CardTitle>
          </CardHeader>
          <CardContent className="p-6 space-y-4">
            <div className="flex justify-between">
              <span className="text-slate-600">Total Consideration</span>
              <span className="font-semibold text-slate-900">${(totalDealValue / 1000).toFixed(1)}B</span>
            </div>
            <div className="flex justify-between">
              <span className="text-slate-600">Premium</span>
              <span className="font-semibold text-slate-900">{scenario.deal_structure?.premium || 0}%</span>
            </div>
            <div className="flex justify-between">
              <span className="text-slate-600">Cash Component</span>
              <span className="font-semibold text-slate-900">
                {scenario.deal_structure?.cash_percentage || 0}% (${(cashComponent / 1000).toFixed(1)}B)
              </span>
            </div>
            <div className="flex justify-between">
              <span className="text-slate-600">Stock Component</span>
              <span className="font-semibold text-slate-900">
                {scenario.deal_structure?.stock_percentage || 0}% (${(stockComponent / 1000).toFixed(1)}B)
              </span>
            </div>
            <div className="flex justify-between">
              <span className="text-slate-600">New Debt Issuance</span>
              <span className="font-semibold text-slate-900">${scenario.deal_structure?.new_debt || 0}M</span>
            </div>
          </CardContent>
        </Card>

        <Card className="border-slate-200">
          <CardHeader className="border-b border-slate-100">
            <CardTitle>Key Assumptions</CardTitle>
          </CardHeader>
          <CardContent className="p-6 space-y-4">
            <div className="flex justify-between">
              <span className="text-slate-600">WACC</span>
              <span className="font-semibold text-slate-900">{scenario.assumptions?.wacc || 0}%</span>
            </div>
            <div className="flex justify-between">
              <span className="text-slate-600">Tax Rate</span>
              <span className="font-semibold text-slate-900">{scenario.assumptions?.tax_rate || 0}%</span>
            </div>
            <div className="flex justify-between">
              <span className="text-slate-600">Expected Closing</span>
              <span className="font-semibold text-slate-900">{scenario.assumptions?.closing_date || 'N/A'}</span>
            </div>
            <div className="flex justify-between">
              <span className="text-slate-600">Synergy Realization</span>
              <span className="font-semibold text-slate-900">{scenario.synergies?.synergy_realization_years || 0} years</span>
            </div>
          </CardContent>
        </Card>
      </div>

      <RiskAssessment type="scenario" data={scenario} context={{ companies }} />

      <AIAnalysis scenario={scenario} acquirer={acquirer} companies={companies} />

      <SynergyBreakdown synergies={scenario.synergies} />
      <ProFormaTable scenario={scenario} acquirer={acquirer} />
    </div>
  );
}