// Generate the portfolio register config (W4-01 / ENT-04).
//
// Source of truth:
//   * src/data/siriusOrgTree.js        - the Sirius subsidiary register
//   * server/config/natureOfBusiness.js - the nature-of-business -> sector map
// The BRD ENT-04 names fifteen portfolio companies; each is matched to its
// subsidiary record where the entity sits inside the Sirius subtree, so its
// sector, geography and capability tags are the registered nature of business
// rather than typed in. Two names (ADI Chain, DDSC) are not in the Sirius
// subtree and are carried with an explicit BRD source.
//
// Run: node scripts/generate_portfolio_register.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

import { SIRIUS_ORGANIZATIONS } from '../src/data/siriusOrgTree.js';
import { classifyNatureOfBusiness, GEOGRAPHY_TAGS } from '../server/config/natureOfBusiness.js';
import { PORTFOLIO_CLUSTER_BY_SECTOR, BRD_PORTFOLIO_NAMES, BRD_ONLY_PORTFOLIO } from '../server/config/portfolioRegisterData.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'server', 'config', 'generatedPortfolioRegister.js');

// capability keywords -> a compact tag list
function capabilityTags(activities, sector) {
  const { matched } = classifyNatureOfBusiness(activities);
  const tags = new Set();
  for (const m of matched || []) if (m && m.length <= 24) tags.add(m);
  if (sector) tags.add(sector.toLowerCase());
  return [...tags].slice(0, 6);
}

function findOrg(pattern) {
  return SIRIUS_ORGANIZATIONS.find((o) => {
    if (o.level === 0) return false;
    if (/below are/i.test(o.name || '')) return false;
    return String(o.name || '').toLowerCase().includes(pattern.toLowerCase());
  }) || null;
}

const rows = [];
for (const spec of BRD_PORTFOLIO_NAMES) {
  const org = spec.pattern ? findOrg(spec.pattern) : null;
  if (!org) {
    const brd = BRD_ONLY_PORTFOLIO.find((b) => b.name === spec.name);
    if (brd) { rows.push({ ...brd, source: 'brd_register', org_id: null }); continue; }
    throw new Error('No register record for BRD portfolio name: ' + spec.name);
  }
  const { sector } = classifyNatureOfBusiness(org.principal_activities);
  const geographies = GEOGRAPHY_TAGS[org.geography] || (org.geography ? [org.geography] : []);
  rows.push({
    name: spec.name,
    legal_name: org.name,
    org_id: org.id,
    cluster: PORTFOLIO_CLUSTER_BY_SECTOR[sector] || 'Other',
    sector,
    geography: geographies[0] || org.geography || null,
    geographies,
    capabilities: capabilityTags(org.principal_activities, sector),
    principal_activities: org.principal_activities || null,
    source: 'subsidiary_register',
  });
}

const body = '// AUTO-GENERATED by scripts/generate_portfolio_register.mjs.\n' +
  '// Derived from the Sirius subsidiary register (src/data/siriusOrgTree.js) and\n' +
  '// the nature-of-business map (server/config/natureOfBusiness.js).\n' +
  '// Do not edit by hand.\n\n' +
  'export const GENERATED_PORTFOLIO_COMPANIES = ' + JSON.stringify(rows, null, 2) + ';\n\n' +
  'export default GENERATED_PORTFOLIO_COMPANIES;\n';
writeFileSync(OUT, body);
console.log('wrote', OUT, rows.length, 'rows');
