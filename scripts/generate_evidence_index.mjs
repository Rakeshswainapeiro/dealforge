// Render a contact sheet of every captured evidence shot into
// docs/evidence/W1-13/admin_evidence_index.png. This is the evidence for
// W1-13 itself: one screen showing the structured path and the shots that
// back each Done TODO.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createRequire } from 'node:module';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const EVIDENCE = path.join(ROOT, 'docs', 'evidence');
const require = createRequire(import.meta.url);

function resolvePlaywright() {
  try { return require('playwright-core'); } catch { /* not a repo dep */ }
  const cache = path.join(process.env.HOME || '', '.npm', '_npx');
  if (fs.existsSync(cache)) {
    for (const entry of fs.readdirSync(cache)) {
      const c = path.join(cache, entry, 'node_modules', 'playwright-core');
      if (fs.existsSync(c)) return require(c);
    }
  }
  throw new Error('playwright-core not found');
}

// W1-13 is this sheet's own folder, so it is left out to avoid nesting a stale
// copy of the index inside itself.
const TODO_ORDER = ['W1-01', 'W1-02', 'W1-03', 'W1-04', 'W1-05', 'W1-06', 'W1-07', 'W1-08', 'W1-09', 'W1-10', 'W1-11', 'W1-12', 'W2-01', 'W2-02', 'W2-03', 'W2-04', 'W2-05', 'W2-06', 'W2-07', 'W2-08', 'W2-09', 'W2-10', 'W3-01', 'W3-02', 'W3-03', 'W3-04', 'W3-05', 'W3-06', 'W3-07', 'W3-08', 'W3-09', 'W3-10', 'W3-11', 'W3-12', 'W3-13', 'W4-01', 'W4-02', 'W4-03', 'W4-04', 'W5-01', 'W5-02', 'W5-03', 'W5-04', 'W5-05', 'W6-01', 'W6-02', 'W6-03', 'W6-04', 'W6-05', 'W6-06', 'W6-07', 'W7-01', 'W7-02', 'W7-03', 'W7-04', 'W7-05', 'W8-01', 'W8-02', 'W8-03', 'W8-04', 'W8-05', 'W8-06', 'W9-01', 'W9-02', 'W9-03', 'W9-04', 'W9-05', 'W9-06'];

function collect() {
  const groups = [];
  for (const id of TODO_ORDER) {
    const dir = path.join(EVIDENCE, id);
    if (!fs.existsSync(dir)) continue;
    const pngs = fs.readdirSync(dir).filter((f) => f.endsWith('.png')).sort();
    if (pngs.length) groups.push({ id, pngs: pngs.map((f) => path.join(dir, f)) });
  }
  return groups;
}

function dataUrl(file) {
  return 'data:image/png;base64,' + fs.readFileSync(file).toString('base64');
}

export async function generate() {
  const groups = collect();
  const cards = groups.map((g) => {
    const cells = g.pngs.map((p) => {
      const label = path.basename(p, '.png');
      return '<figure class="shot"><img src="' + dataUrl(p) + '"/><figcaption>' + label + '</figcaption></figure>';
    }).join('');
    return '<section class="group"><h2>' + g.id + ' <span class="n">' + g.pngs.length + ' shot' + (g.pngs.length === 1 ? '' : 's') + '</span></h2><div class="grid">' + cells + '</div></section>';
  }).join('');

  const html = '<!doctype html><html><head><meta charset="utf-8"><style>' +
    'body{font-family:-apple-system,Segoe UI,Roboto,sans-serif;margin:0;padding:32px;background:#0f172a;color:#e2e8f0}' +
    'h1{font-size:26px;margin:0 0 4px}p.sub{color:#94a3b8;margin:0 0 24px}' +
    '.group{margin-bottom:28px}h2{font-size:18px;border-bottom:1px solid #334155;padding-bottom:6px}' +
    '.n{color:#94a3b8;font-weight:400;font-size:13px}' +
    '.grid{display:grid;grid-template-columns:repeat(2,1fr);gap:16px;margin-top:12px}' +
    '.shot{margin:0;background:#1e293b;border:1px solid #334155;border-radius:10px;overflow:hidden}' +
    '.shot img{display:block;width:100%}figcaption{padding:8px 10px;font-size:13px;color:#cbd5e1;font-family:ui-monospace,monospace}' +
    '</style></head><body>' +
    '<h1>DealForge evidence index</h1>' +
    '<p class="sub">docs/evidence/&lt;TODO-ID&gt;/&lt;persona&gt;_&lt;feature&gt;.png \u00b7 generated by scripts/generate_evidence_index.mjs</p>' +
    cards + '</body></html>';

  const pw = resolvePlaywright();
  const browser = await pw.chromium.launch({ channel: 'chrome', headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1400, height: 1000 } });
    await page.setContent(html, { waitUntil: 'load' });
    await page.waitForTimeout(500);
    const outDir = path.join(EVIDENCE, 'W1-13');
    fs.mkdirSync(outDir, { recursive: true });
    const out = path.join(outDir, 'admin_evidence_index.png');
    await page.screenshot({ path: out, fullPage: true });
    return { out: path.relative(ROOT, out), groups };
  } finally {
    await browser.close();
  }
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  generate().then((r) => {
    console.log('wrote', r.out);
    for (const g of r.groups) console.log(' ', g.id, g.pngs.length);
  }).catch((e) => { console.error(e); process.exit(1); });
}
