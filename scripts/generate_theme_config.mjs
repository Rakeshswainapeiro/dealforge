// Generate the data-derived investment theme config from the Sirius subsidiary
// register.
//
// Source: src/data/siriusOrgTree.js (principal_activities = nature of business)
//         server/config/natureOfBusiness.js (the classification map)
// Output: server/config/derivedThemes.js
//
// Run: node scripts/generate_theme_config.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

import { SIRIUS_ORGANIZATIONS } from '../src/data/siriusOrgTree.js';
import { deriveThemesFromOrgs } from '../server/config/natureOfBusiness.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'server', 'config', 'derivedThemes.js');

// Mandate-holding entities: operating subsidiaries and intermediate holdings at
// level 1 and 2 that carry a real registered activity (pure shells are skipped
// by the deriver). Deeper entities inherit their ancestor's mandate through
// getEffectiveTheme, so seeding them individually would only add noise.
const themes = deriveThemesFromOrgs(SIRIUS_ORGANIZATIONS, { levels: [1, 2] });

const body = themes
  .map(
    (t) =>
      '  {\n' +
      `    org_id: '${t.org_id}',\n` +
      `    sector: '${t.sector}',\n` +
      `    keywords: ${JSON.stringify(t.keywords)},\n` +
      `    geographies: ${JSON.stringify(t.geographies)},\n` +
      `    description: ${JSON.stringify(t.description)},\n` +
      '  },'
  )
  .join('\n');

const file = `// AUTO-GENERATED by scripts/generate_theme_config.mjs.
//
// Derived from the registered nature of business in the Sirius subsidiary
// register (src/data/siriusOrgTree.js) using the classification map in
// server/config/natureOfBusiness.js. Do not edit by hand.
//
// Regenerate with: node scripts/generate_theme_config.mjs

export const DERIVED_THEMES = [
${body}
];

export default DERIVED_THEMES;
`;

writeFileSync(OUT, file, 'utf8');
console.log(`wrote ${themes.length} derived themes -> ${OUT}`);
